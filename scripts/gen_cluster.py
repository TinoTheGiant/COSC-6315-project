"""Generate the Docker Compose file and the netem rules from the simulator's own
RTT matrix.

The point is parity. ADR-0009 requires the simulator and the cluster to agree on
geography, and ADR-0011 makes that structural rather than a matter of
discipline: both read `topology.DEFAULT_RTT_MS`, so they cannot drift. Editing
the matrix and re-running this script is the only way to change the cluster's
geography.

Usage:
    python scripts/gen_cluster.py                 # writes docker/docker-compose.yml
    python scripts/gen_cluster.py --regions 4     # the laptop fallback
"""
from __future__ import annotations

import argparse
from pathlib import Path

from fragalloc.config import FragAllocConfig
from fragalloc.topology import DEFAULT_RTT_MS

SUBNET = "172.28.0.0/16"
BASE_IP = "172.28.0."
FIRST_OCTET = 11          # node i lives at 172.28.0.(11 + i)
SQL_PORT = 26257
HTTP_PORT = 8080


def node_ip(i: int) -> str:
    return f"{BASE_IP}{FIRST_OCTET + i}"


def build(n_regions: int, cache: str, sql_mem: str) -> str:
    cfg = FragAllocConfig()
    names = list(cfg.topology.region_names)[:n_regions]
    if len(names) < n_regions:
        raise SystemExit(f"only {len(names)} regions configured, asked for {n_regions}")

    join = ",".join(f"{node_ip(i)}:{SQL_PORT}" for i in range(n_regions))
    lines = [
        "# GENERATED by scripts/gen_cluster.py. Do not edit.",
        "# Geography comes from fragalloc.topology.DEFAULT_RTT_MS so the cluster and",
        "# the simulator cannot disagree. Change the matrix, re-run the generator.",
        "",
        "services:",
    ]

    for i, name in enumerate(names):
        # netem shapes egress only, so each side carries half the round trip.
        rules = ";".join(
            f"{node_ip(j)}={DEFAULT_RTT_MS[i][j] / 2.0:g}"
            for j in range(n_regions) if j != i
        )
        lines += [
            f"  node{i}:",
            "    build:",
            "      context: .",
            "      dockerfile: Dockerfile.crdb",
            f"    container_name: crdb-{name}",
            "    cap_add: [NET_ADMIN]",
            "    environment:",
            f'      NETEM_RULES: "{rules}"',
            "    command: >",
            "      start --insecure",
            f"      --advertise-addr={node_ip(i)}:{SQL_PORT}",
            f"      --listen-addr=0.0.0.0:{SQL_PORT}",
            f"      --http-addr=0.0.0.0:{HTTP_PORT}",
            f"      --join={join}",
            f"      --locality=region={name}",
            f"      --cache={cache} --max-sql-memory={sql_mem}",
            "      --store=/cockroach/data",
            "    volumes:",
            f"      - node{i}-data:/cockroach/data",
            "    ports:",
            f"      - \"{SQL_PORT + i}:{SQL_PORT}\"",
            f"      - \"{HTTP_PORT + i}:{HTTP_PORT}\"",
            "    networks:",
            "      crdb:",
            f"        ipv4_address: {node_ip(i)}",
            "",
        ]

    lines += [
        "volumes:",
        *[f"  node{i}-data:" for i in range(n_regions)],
        "",
        "networks:",
        "  crdb:",
        "    driver: bridge",
        "    ipam:",
        "      config:",
        f"        - subnet: {SUBNET}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--regions", type=int, default=6,
                    help="must match the simulator's region count (ADR-0009 parity)")
    ap.add_argument("--cache", default="128MiB")
    ap.add_argument("--max-sql-memory", default="256MiB")
    ap.add_argument("-o", "--out", default="docker/docker-compose.yml")
    args = ap.parse_args()

    text = build(args.regions, args.cache, args.max_sql_memory)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")

    total = args.regions
    print(f"wrote {out}  ({total} regions)")
    print(f"  memory budget: {total} x (cache {args.cache} + sql {args.max_sql_memory})")
    print(f"  init with:     scripts/cluster.sh up")
    print(f"  VERIFY LATENCY before trusting any measurement:")
    print(f"    docker exec crdb-{FragAllocConfig().topology.region_names[0]} "
          f"ping -c3 {node_ip(1)}")


if __name__ == "__main__":
    main()
